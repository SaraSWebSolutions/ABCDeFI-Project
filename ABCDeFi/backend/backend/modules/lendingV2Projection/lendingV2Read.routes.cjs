const express = require('express');
const { loadLendingV2Manifest } = require('../../config/lendingV2Manifest.cjs');
const { loadLendingV2Artifacts } = require('../../config/lendingV2Artifacts.cjs');
const models = require('./models.cjs');
const { loadBackendRuntimeFamily } = require('../../config/runtimeFamily.cjs');
const { ONE_Q_LOCAL_B64_LIFECYCLE_TEST } = require('../../config/oneQLocalB64LifecycleTestRuntime.cjs');
const { createB64CheckpointModels } = require('../../config/b64CheckpointModels.cjs');
const { createLendingV2ReadController } = require('./lendingV2Read.controller.cjs');
const runtime = loadBackendRuntimeFamily();
const boundModels = runtime.family === ONE_Q_LOCAL_B64_LIFECYCLE_TEST ? createB64CheckpointModels({ runtime }).models : models;
const controller = createLendingV2ReadController({ manifest: loadLendingV2Manifest(), artifacts: loadLendingV2Artifacts(), models: boundModels });
const router = express.Router();
router.get('/status', controller.status);
router.get('/reserve', controller.reserve);
router.get('/requests/open', controller.openRequests);
router.get('/referrals/:address', controller.referral);
router.get('/requests/:requestId', controller.request);
router.get('/wallet/:address', controller.wallet);
router.get('/certificates/wallet/:address', controller.walletCertificates);
router.get('/certificates/loans/:loanId', controller.loanCertificates);
router.get('/certificates/:tokenId/history', controller.certificateHistory);
router.get('/certificates/:tokenId', controller.certificate);
router.get('/loans/:loanId', controller.loan);
router.get('/loans/:loanId/history', controller.history);
router.get('/loans/:loanId/preview', controller.preview);
module.exports = router;
